/**
 * Deterministic RNG. The whole scene must be reproducible: the same seed has to
 * yield the same sculpture on every reload, on every machine, so that art
 * direction decisions are stable and reviewable.
 */
export function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
